// Helper functions
export const getProductById = (id) => {
  return products.find(product => product.id === parseInt(id))
}

export const getProductsByCategory = (category) => {
  if (category === 'all') return products
  return products.filter(product => product.category === category)
}

export const getFeaturedProducts = () => {
  return products.filter(product => product.badge === 'Best Seller').slice(0, 4)
}

export const getNewArrivals = () => {
  return products.filter(product => product.badge === 'New').slice(0, 4)
}

export const getSaleProducts = () => {
  return products.filter(product => product.badge === 'Sale').slice(0, 4)
}

export const getEcoFriendlyProducts = () => {
  return products.filter(product => product.badge === 'Eco-Friendly')
}

export const searchProducts = (query) => {
  const searchTerm = query.toLowerCase()
  return products.filter(product => 
    product.name.toLowerCase().includes(searchTerm) ||
    product.description.toLowerCase().includes(searchTerm) ||
    product.category.toLowerCase().includes(searchTerm)
  )
}

export const getProductsByPriceRange = (min, max) => {
  return products.filter(product => product.price >= min && product.price <= max)
}

export const getProductsByRating = (minRating) => {
  return products.filter(product => product.rating >= minRating)
}

export const sortProducts = (productsArray, sortBy) => {
  const sorted = [...productsArray]
  switch (sortBy) {
    case 'price-low':
      return sorted.sort((a, b) => a.price - b.price)
    case 'price-high':
      return sorted.sort((a, b) => b.price - a.price)
    case 'rating':
      return sorted.sort((a, b) => b.rating - a.rating)
    case 'name':
      return sorted.sort((a, b) => a.name.localeCompare(b.name))
    default:
      return sorted
  }
}

